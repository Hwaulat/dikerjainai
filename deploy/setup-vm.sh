#!/usr/bin/env bash
# ==============================================================================
# One-time Target VM Setup Script for kefir-clinic-dashboard
# Run this on your production Ubuntu/Debian VM as root or sudo:
#   curl -sSL <raw-url>/setup-vm.sh | bash
#   or: bash deploy/setup-vm.sh
# ==============================================================================

set -euo pipefail

APP_NAME="kefir-clinic-dashboard"
DEPLOY_DIR="/opt/dockerapp/${APP_NAME}"

echo "🚀 Initializing deployment environment at ${DEPLOY_DIR}..."

# 1. Create deployment and persistent state directories
mkdir -p "${DEPLOY_DIR}/data"
mkdir -p "${DEPLOY_DIR}/wa_assistant_auth"
mkdir -p "${DEPLOY_DIR}/logs"

# 2. Check Docker and Docker Compose
if ! command -v docker &> /dev/null; then
    echo "⚠️ Docker is not installed. Please install Docker Engine first."
    exit 1
fi

if ! docker compose version &> /dev/null; then
    echo "⚠️ Docker Compose v2 is not installed. Please install docker-compose-plugin."
    exit 1
fi

# 3. Create initial .env if not exists
if [ ! -f "${DEPLOY_DIR}/.env" ]; then
    echo "📝 Creating initial ${DEPLOY_DIR}/.env..."
    SESSION_SECRET=$(openssl rand -hex 32)
    cat <<EOF > "${DEPLOY_DIR}/.env"
# Auto-generated by setup-vm.sh on $(date)
PORT=3344
APP_PORT=3344
CONTAINER_NAME=kefir_clinic_dashboard
DOCKER_IMAGE_TAG=registry.gitlab.com/dev-ragdalion/kefir-clinic-dashboard:latest
NODE_ENV=production
TZ=Asia/Jakarta

# Security Secret
KEFIR_SESSION_SECRET=${SESSION_SECRET}

# Neosoft & External Integrations (Fill these in!)
NEOSOFT_TOKEN=
NINEROUTER_HOST=host.docker.internal
NINEROUTER_PORT=20129
NINEROUTER_MODEL=utama
NINEROUTER_API_KEY=

META_APP_ID=
META_APP_SECRET=
META_AD_ACCOUNT_ID=
META_ACCESS_TOKEN=

GOOGLE_MAPS_API_KEY=
TELEGRAM_BOT_TOKEN=
TELEGRAM_CHAT_ID=
EOF
    echo "✅ .env created with random KEFIR_SESSION_SECRET."
else
    echo "ℹ️ ${DEPLOY_DIR}/.env already exists, skipping creation."
fi

# 4. Set correct ownership (UID 1000 is 'node' inside standard container)
echo "🔒 Setting permissions for non-root container (UID 1000:1000)..."
chown -R 1000:1000 "${DEPLOY_DIR}/data" "${DEPLOY_DIR}/wa_assistant_auth" "${DEPLOY_DIR}/logs"
chmod 750 "${DEPLOY_DIR}/data" "${DEPLOY_DIR}/wa_assistant_auth" "${DEPLOY_DIR}/logs"
chmod 600 "${DEPLOY_DIR}/.env"

echo "🎉 VM directory initialization complete!"
echo "Next steps:"
echo " 1. Copy docker-compose.yml to ${DEPLOY_DIR}/docker-compose.yml"
echo " 2. Populate credentials in ${DEPLOY_DIR}/.env"
echo " 3. Configure GitLab CI/CD Variables (SSH_HOST, SSH_USER, SSH_PRIVATE_KEY, DEPLOY_PATH)"
echo " 4. Push to 'main' branch to trigger first automated deployment."
